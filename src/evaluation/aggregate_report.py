"""Cross-model aggregation — one comparison report over every evaluated track.

Scans ``src/evaluation/results/<track>/`` for the per-section ``result.json`` files each
track's ``run_eval`` wrote and builds a single side-by-side markdown report: a leaderboard
plus one comparison table per section (A–J). Read-only; produces
``results/COMPARISON.md`` (and JSON).

    PYTHONPATH=src python3 -m evaluation.aggregate_report
"""
from __future__ import annotations

import glob
import json
import os

from evaluation import core

RESULTS = core.RESULTS_ROOT


def _load_track(track_dir):
    out = {"track": os.path.basename(track_dir), "sections": {}}
    for rj in glob.glob(os.path.join(track_dir, "*", "result.json")):
        try:
            with open(rj) as f:
                r = json.load(f)
            out["sections"][r["section"]] = r
        except Exception:
            pass
    sj = os.path.join(track_dir, "summary.json")
    if os.path.exists(sj):
        with open(sj) as f:
            out["summary"] = json.load(f)
    return out


def _g(sec, *keys, default="—"):
    """Nested get from a section's headline/data."""
    if sec is None:
        return default
    for src in (sec.get("headline", {}), sec.get("data", {})):
        cur = src
        ok = True
        for k in keys:
            if isinstance(cur, dict) and k in cur:
                cur = cur[k]
            else:
                ok = False
                break
        if ok:
            return cur
    return default


def _num(v):
    return f"{v:.3f}" if isinstance(v, (int, float)) else str(v)


def build():
    tracks = []
    for d in sorted(glob.glob(os.path.join(RESULTS, "*"))):
        if os.path.isdir(d) and glob.glob(os.path.join(d, "*", "result.json")):
            tracks.append(_load_track(d))
    if not tracks:
        raise SystemExit(f"no evaluated tracks under {RESULTS}")
    names = [t["track"] for t in tracks]

    L = ["# Cross-model evaluation comparison", "",
         f"*{len(tracks)} models · generated by `evaluation.aggregate_report`*", "",
         "Reflected-light / direct-imaging retrieval (0.2–2.0 µm). Sections **E** (solar-system) "
         "and **F** (real Earth) are the only LITERAL-ground-truth real tests; **G** and the "
         "'far' rows of **H** are wrong-observable OOD probes, not accuracy.", "",
         "## Models", ""]
    for t in tracks:
        prov = t.get("summary", {}).get("provenance", {})
        secs = [s for s, v in t["sections"].items() if v.get("status") in ("ok", "preliminary")]
        L.append(f"- **{t['track']}** — {len(secs)} sections, "
                 f"{prov.get('epochs_run', '?')}/{prov.get('epochs_planned', '?')} epochs, "
                 f"n_seeds={t.get('summary', {}).get('n_seeds', '?')}")
    L.append("")

    def table(title, header, rowfn, note=""):
        L.append(f"## {title}")
        if note:
            L.append(f"*{note}*")
        L.append("")
        L.append("| model | " + " | ".join(header) + " |")
        L.append("|" + "---|" * (len(header) + 1))
        for t in tracks:
            L.append(f"| {t['track']} | " + " | ".join(_num(x) for x in rowfn(t)) + " |")
        L.append("")

    def sec(t, letter):
        return t["sections"].get(letter)

    # A — in-distribution
    table("A · In-distribution accuracy",
          ["R²_covered ref", "R²_all12 ref", "R²_covered α=1", "RMSE α=1 (dex)"],
          lambda t: [_g(sec(t, "A"), "R2_covered noiseless-ref (a=300)"),
                     _g(sec(t, "A"), "R2_all12 noiseless-ref"),
                     _g(sec(t, "A"), "R2_covered @a=1"),
                     _g(sec(t, "A"), "RMSE_all12 (dex) @a=1")],
          "noiseless reference = information ceiling of the observable.")

    # B — baselines
    table("B · Beats the linear (Ridge) floor?",
          ["neural α=1 R²", "Ridge floor", "beats floor"],
          lambda t: [_g(sec(t, "B"), "neural_all12_R2@a1"), _g(sec(t, "B"), "Ridge_floor_R2"),
                     _g(sec(t, "B"), "beats_linear_floor")])

    # C — cross-generator
    table("C · Cross-generator domain gap (covered R², noiseless ref)",
          ["native INARA", "pRT", "TauREx"],
          lambda t: [_g(sec(t, "C"), "native_R2_covered_ref"),
                     _g(sec(t, "C"), "prt_R2_covered_ref"),
                     _g(sec(t, "C"), "taurex_R2_covered_ref")],
          "large drop from native ⇒ overfit to PSG physics (gate on D, decompose in J).")

    # D — PSG anchor
    table("D · PSG anchor (eval-path control)",
          ["anchor R²_covered", "anchor/native", "PASS ≥0.9×"],
          lambda t: [_g(sec(t, "D"), "anchor_R2_covered_ref"), _g(sec(t, "D"), "anchor/native"),
                     _g(sec(t, "D"), "PASS(≥0.9×)")],
          "anchor≈native ⇒ the cross-gen collapse in C is a real generator effect, not an eval-path bug.")

    # E — solar system
    table("E · Solar-System-as-exoplanet (LITERAL ground truth)",
          ["dominant✓ (terr.)", "mean dex-err (terr.)"],
          lambda t: [_g(sec(t, "E"), "dominant-gas correct (terrestrial)"),
                     _g(sec(t, "E"), "mean dex-err covered (terrestrial)")],
          "honesty probe (giants must not fabricate O2/O3) is per-model in each report.md.")

    # F — real Earth
    table("F · Real disk-integrated Earth (VPL, real photons)",
          ["dominant pred", "dominant✓", "dex-err (covered)", "ordering ρ"],
          lambda t: [_g(sec(t, "F"), "dominant pred"), _g(sec(t, "F"), "dominant correct"),
                     _g(sec(t, "F"), "mean dex-err (covered)"), _g(sec(t, "F"), "ordering ρ")])

    # G — OOD probe
    table("G · Transiting OOD probe (anomaly vs INARA)",
          ["INARA anomaly median", "INARA anomaly p95"],
          lambda t: [_g(sec(t, "G"), "INARA anomaly median"), _g(sec(t, "G"), "INARA anomaly p95")],
          "per-input × INARA-median in each report.md; high = correctly seen as off-distribution.")

    # H — published
    table("H · Published-retrieval (near-domain, direct-imaging only)",
          ["n near-domain", "mean dex-err (near)"],
          lambda t: [_g(sec(t, "H"), "n_near-domain (direct-imaging)"),
                     _g(sec(t, "H"), "mean dex-err (near-domain)")],
          "'far' (transmission) rows are OOD context, not accuracy — see per-model report.md.")

    # I — calibration
    table("I · Posterior calibration (MC-dropout)",
          ["cov68 (want .68)", "cov95 (want .95)", "reliability ECE", "TARP ECE"],
          lambda t: [_g(sec(t, "I"), "coverage_68 (active)"), _g(sec(t, "I"), "coverage_95 (active)"),
                     _g(sec(t, "I"), "reliability_ECE"), _g(sec(t, "I"), "TARP_ECE")],
          "cov ≪ nominal ⇒ overconfident. Single-seed MC-dropout under-disperses — PRELIMINARY.")

    # J — OOD honesty
    table("J · OOD honesty verdict",
          ["pRT verdict", "TauREx verdict", "PSG verdict"],
          lambda t: [_g(sec(t, "J"), "prt_verdict"), _g(sec(t, "J"), "taurex_verdict"),
                     _g(sec(t, "J"), "psg_verdict")])

    L += ["## How to read this", "",
          "- **A/B** measure raw accuracy; **C/D/J** whether it generalizes past PSG physics; "
          "**E/F** whether it recovers *real* known compositions; **G/H** honest OOD behaviour; "
          "**I** whether its uncertainty is trustworthy.",
          "- Single-seed runs are **preliminary** (no across-seed variance; calibration under-dispersed). "
          "Train ≥3 seeds for citable numbers.",
          "- Per-model detail (per-species tables, honesty probes, plots) is in "
          "`results/<model>/report.md`.", ""]

    out_md = os.path.join(RESULTS, "COMPARISON.md")
    with open(out_md, "w") as f:
        f.write("\n".join(L) + "\n")
    out_json = os.path.join(RESULTS, "COMPARISON.json")
    with open(out_json, "w") as f:
        json.dump({t["track"]: {s: v.get("headline", {}) for s, v in t["sections"].items()}
                   for t in tracks}, f, indent=2, default=core._json_default)
    print(f"wrote {out_md}\nwrote {out_json}\nmodels: {names}")
    return out_md


if __name__ == "__main__":
    build()
